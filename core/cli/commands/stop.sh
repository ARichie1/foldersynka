#!/data/data/com.termux/files/usr/bin/bash

###############################################################################
# FolderSynka
# File: core/cli/commands/stop.sh
#
# Description:
#   Stop synchronization for a profile.
###############################################################################

set -euo pipefail

###############################################################################
# Dependencies
###############################################################################

source "${FS_HOME}/core/config/config.sh"
source "${FS_HOME}/core/validation/pipeline.sh"
source "${FS_HOME}/core/services/service-generator.sh"

###############################################################################
# Help
###############################################################################

fs_stop_help() {

    cat <<EOF

Stop a FolderSynka synchronization service.

Usage

    foldersynka stop <profile>

EOF

}

###############################################################################
# Main
###############################################################################

fs_command_stop() {

    if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
        fs_stop_help
        return 0
    fi

    local profile="${1:-}"

    if [[ -z "$profile" ]]; then
        fs_stop_help
        return 1
    fi

    ###########################################################################
    # Validation
    ###########################################################################

    fs_run_validation_pipeline \
        stop \
        "$profile"

    ###########################################################################
    # Service
    ###########################################################################

    fs_service_stop "$profile"

}

###############################################################################
# Execute
###############################################################################

fs_command_stop "$@"