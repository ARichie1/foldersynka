#!/data/data/com.termux/files/usr/bin/bash

###############################################################################
# FolderSynka
# File: core/cli/commands/restart.sh
#
# Description:
#   Restart synchronization for a profile.
###############################################################################

set -euo pipefail

###############################################################################
# Dependencies
###############################################################################

source "${FS_HOME}/core/config/config.sh"
source "${FS_HOME}/core/validation/pipeline.sh"
source "${FS_HOME}/core/services/service-generator.sh"

###############################################################################
# Help
###############################################################################

fs_restart_help() {

    cat <<EOF

Restart a FolderSynka synchronization service.

Usage

    foldersynka restart <profile>

EOF

}

###############################################################################
# Main
###############################################################################

fs_command_restart() {

    if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
        fs_restart_help
        return 0
    fi

    local profile="${1:-}"

    if [[ -z "$profile" ]]; then
        fs_restart_help
        return 1
    fi

    ###########################################################################
    # Validate Current State
    ###########################################################################

    fs_run_validation_pipeline \
        stop \
        "$profile"

    ###########################################################################
    # Stop
    ###########################################################################

    fs_service_stop "$profile"

    ###########################################################################
    # Validate Start
    ###########################################################################

    fs_run_validation_pipeline \
        start \
        "$profile"

    ###########################################################################
    # Start
    ###########################################################################

    fs_service_start "$profile"

}

###############################################################################
# Execute
###############################################################################

fs_command_restart "$@"