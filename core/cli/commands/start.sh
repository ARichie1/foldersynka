#!/data/data/com.termux/files/usr/bin/bash

###############################################################################
# FolderSynka
# File: core/cli/commands/start.sh
#
# Description:
#   Start synchronization for a profile.
###############################################################################

set -euo pipefail

###############################################################################
# Dependencies
###############################################################################

source "${FS_HOME}/core/config/config.sh"
source "${FS_HOME}/core/validation/pipeline.sh"
source "${FS_HOME}/core/services/service-generator.sh"

###############################################################################
# Help
###############################################################################

fs_start_help() {

    cat <<EOF

Start a FolderSynka synchronization service.

Usage

    foldersynka start <profile>

EOF

}

###############################################################################
# Main
###############################################################################

fs_command_start() {

    if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
        fs_start_help
        return 0
    fi

    local profile="${1:-}"

    if [[ -z "$profile" ]]; then
        fs_start_help
        return 1
    fi

    ###########################################################################
    # Validation
    ###########################################################################

    fs_run_validation_pipeline \
        start \
        "$profile"

    ###########################################################################
    # Service
    ###########################################################################

    fs_service_start "$profile"

}

###############################################################################
# Execute
###############################################################################

fs_command_start "$@"