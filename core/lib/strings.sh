###############################################################################

set -euo pipefail

###############################################################################
# Case Conversion
###############################################################################

fs_to_lower() {
    printf '%s' "$1" |
        tr '[:upper:]' '[:lower:]'
}

fs_to_upper() {
    printf '%s' "$1" |
        tr '[:lower:]' '[:upper:]'
}

###############################################################################
# Trim
###############################################################################

fs_trim() {
    local value="$1"

    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"

    printf '%s' "$value"
}

###############################################################################
# Checks
###############################################################################

fs_is_empty() {
    [[ -z "${1:-}" ]]
}

fs_is_not_empty() {
    [[ -n "${1:-}" ]]
}

fs_starts_with() {
    [[ "$1" == "$2"* ]]
}

fs_ends_with() {
    [[ "$1" == *"$2" ]]
}

fs_contains() {
    [[ "$1" == *"$2"* ]]
}

###############################################################################
# Formatting
###############################################################################

fs_repeat() {
    local char="$1"
    local count="$2"

    printf '%*s' "$count" '' |
        tr ' ' "$char"
}

###############################################################################
# Slugify
###############################################################################

fs_slugify() {
    printf '%s' "$1" |
        tr '[:upper:]' '[:lower:]' |
        sed 's/[^a-z0-9]/-/g' |
        tr -s '-'
}

