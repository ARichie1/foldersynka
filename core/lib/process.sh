# Description:
#   Generic process and signal utilities.
#
# Responsibilities:
#   • Process identification
#   • Process existence checks
#   • Signal handling
#   • Background execution
#   • Waiting
#   • Generic lock-file primitives
#
###############################################################################

set -euo pipefail

###############################################################################
# PID
###############################################################################

fs_current_pid() {
    printf '%s\n' "$$"
}

fs_process_exists() {
    local pid="$1"

    kill -0 "$pid" 2>/dev/null
}

###############################################################################
# Signals
###############################################################################

fs_send_signal() {
    local signal="$1"
    local pid="$2"

    kill "-$signal" "$pid"
}

fs_kill() {
    fs_send_signal TERM "$1"
}

fs_kill_force() {
    fs_send_signal KILL "$1"
}

###############################################################################
# Background
###############################################################################

fs_background() {
    "$@" &
}

###############################################################################
# Wait
###############################################################################

fs_wait() {
    wait "$1"
}

###############################################################################
# Generic Lock Files
###############################################################################

fs_lock_create() {
    local file="$1"

    printf '%s\n' "$$" > "$file"
}

fs_lock_remove() {
    rm -f -- "$1"
}

fs_lock_exists() {
    [[ -f "$1" ]]
}

